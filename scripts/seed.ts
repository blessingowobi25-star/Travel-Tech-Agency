import { loadEnvFile } from './load-env';
import { migrate } from '../src/db/migrate';
import { resetDb } from '../src/db/client';
import { findUserByEmail, registerUser } from '../src/lib/auth/service';
import {
  getDestinationBySlug,
  upsertDestination,
} from '../src/repositories/destinations';
import { createEnquiry, listEnquiries } from '../src/repositories/enquiries';
import { createQuote } from '../src/repositories/quotes';
import { createOrder, listOrdersByUser } from '../src/repositories/orders';
import { logger } from '../src/lib/logger';
import { seedDestinations, seedUsers } from './seed-data';

loadEnvFile();

/**
 * Flags
 *   --skip-users        do not create the demo accounts
 *   --skip-demo         do not create the demo enquiry / quote / order
 *   --only-destinations only refresh the destination catalogue
 */
const args = new Set(process.argv.slice(2));
const skipUsers = args.has('--skip-users');
const skipDemo = args.has('--skip-demo');
const onlyDestinations = args.has('--only-destinations');

/** Marker written into the demo enquiry so repeat runs can find it. */
const DEMO_MARKER = '[seed:demo-journey]';

async function seedDestinationCatalogue() {
  let created = 0;
  let updated = 0;

  for (const destination of seedDestinations) {
    const existed = await getDestinationBySlug(destination.slug);
    await upsertDestination(destination);
    if (existed) updated += 1;
    else created += 1;
  }

  console.log(`Destinations: ${created} created, ${updated} updated.`);
  return created + updated;
}

async function seedDemoUsers() {
  const created: string[] = [];
  const skipped: string[] = [];

  for (const user of seedUsers) {
    const existing = await findUserByEmail(user.email);
    if (existing) {
      skipped.push(`${user.email} (${existing.role})`);
      continue;
    }
    await registerUser(user);
    created.push(`${user.email} (${user.role})`);
  }

  console.log(`Users created: ${created.length ? created.join(', ') : 'none'}`);
  if (skipped.length) console.log(`Users already present: ${skipped.join(', ')}`);
  return created;
}

async function seedDemoJourney() {
  const customer = await findUserByEmail('customer@waymark.test');
  if (!customer) {
    console.log('Demo journey skipped: the demo customer does not exist.');
    return;
  }

  const existingEnquiries = await listEnquiries({ userId: customer.id });
  const alreadyThere = existingEnquiries.some((e) => e.details.includes(DEMO_MARKER));
  if (alreadyThere) {
    const orders = await listOrdersByUser(customer.id);
    console.log(
      `Demo journey already present${orders[0] ? ` (order ${orders[0].reference})` : ''}.`,
    );
    return;
  }

  const lagos = await getDestinationBySlug('lagos-lagos');
  if (!lagos) {
    console.log('Demo journey skipped: the Lagos destination is missing.');
    return;
  }

  const enquiry = await createEnquiry({
    userId: customer.id,
    service: 'holiday',
    contactName: customer.fullName,
    contactEmail: customer.email,
    contactPhone: '+2348000000003',
    partySize: 2,
    departureCity: 'Lagos',
    travelStartDate: '2026-12-19',
    flexibility: 'flexible',
    budgetAmount: 180000,
    budgetCurrency: 'NGN',
    details:
      `${DEMO_MARKER} Two of us, first trip organised properly. We want Lagos for a ` +
      'long weekend with some culture, food and one beach day. No rush on the dates.',
    destinationId: lagos.id,
  });

  const quote = await createQuote({
    enquiryId: enquiry.id,
    userId: customer.id,
    currency: 'NGN',
    items: [
      {
        description: 'Hotel accommodation - 3 nights, Lekki/Victoria Island',
        quantity: 3,
        unitPrice: 32000,
        amount: 96000,
        category: 'accommodation',
      },
      {
        description: 'Airport transfer and inter-neighbourhood transport',
        quantity: 1,
        unitPrice: 24000,
        amount: 24000,
        category: 'transport',
      },
      {
        description: 'Guided city, food and beach experience day',
        quantity: 1,
        unitPrice: 30000,
        amount: 30000,
        category: 'activities',
      },
      {
        description: 'Service fee',
        quantity: 1,
        unitPrice: 15000,
        amount: 15000,
        category: 'fees',
      },
    ],
    fees: 0,
    terms:
      'Prices follow the current 2026 rate sheet and hold for 14 days. Payment is due in full before departure.',
    notes: 'Demo quote generated by the seed script.',
    expiresAt: new Date(Date.now() + 14 * 24 * 3600_000).toISOString(),
    status: 'SENT',
  });

  const order = await createOrder({
    quoteId: quote.id,
    enquiryId: enquiry.id,
    userId: customer.id,
    currency: quote.currency,
    items: quote.items.map(({ description, quantity, unitPrice, amount, category }) => ({
      description,
      quantity,
      unitPrice,
      amount,
      category,
    })),
    fees: quote.fees,
    status: 'AWAITING_PAYMENT',
    payable: true,
  });

  console.log(
    `Demo journey created: enquiry ${enquiry.reference}, quote ${quote.reference}, order ${order.reference} (${order.total} ${order.currency}).`,
  );
}

async function main() {
  console.log('Applying schema...');
  const migration = await migrate();
  console.log(`Schema ready (${migration.dialect}, ${migration.applied.length} tables).`);

  await seedDestinationCatalogue();

  if (!onlyDestinations) {
    if (!skipUsers) await seedDemoUsers();
    if (!skipDemo) await seedDemoJourney();
  }

  logger.info('seed.completed', { destinations: seedDestinations.length });
  console.log('Seed complete.');
}

main()
  .catch((error) => {
    console.error('Seed failed:', error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await resetDb();
  });
